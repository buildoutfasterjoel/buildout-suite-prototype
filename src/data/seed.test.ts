const START = '2026-01-01T00:00:00.000Z'

describe('generateTasks', () => {
  it('returns the proposal setup checklist, auto-generated items complete', () => {
    const tasks = generateTasks('proposal', START)
    expect(tasks.map((t) => t.label)).toEqual([
      'Underwriting',
      'Listing proposal',
      "Broker's Opinion of Value",
      'Call owner to confirm pricing strategy',
      'Upload executed listing agreement',
      'Order professional photography',
      'Order property signage',
      'Publish listing to website',
    ])
    expect(tasks.slice(0, 3).every((t) => t.status === 'complete' && t.autoGenerated)).toBe(true)
    expect(tasks.slice(3).every((t) => t.status === 'open')).toBe(true)
  })

  it('returns active-stage marketing tasks', () => {
    const tasks = generateTasks('active', START)
    expect(tasks.map((t) => t.label)).toEqual([
      'Send marketing package',
      'Email updated marketing package to prospects',
      'Schedule property tours',
      'Review incoming offers',
      'Confirm due diligence dates',
    ])
  })

  it('returns the contract-to-close checklist for under-contract, all open', () => {
    const tasks = generateTasks('under-contract', START)
    expect(tasks.map((t) => t.label)).toEqual([
      'Execute purchase agreement (PSA)',
      'Collect earnest money',
      'Meeting with title company on closing logistics',
      'Complete due diligence',
      'Finalize buyer financing',
      'Clear closing contingencies',
      'Prepare closing documents',
      'Set agreed closing date',
    ])
    expect(tasks.filter((t) => t.status === 'complete')).toHaveLength(0)
  })

  it('returns the brokerage back-office checklist for closed', () => {
    const tasks = generateTasks('closed', START)
    expect(tasks.map((t) => t.label)).toEqual([
      'Review voucher',
      'Set up pre-split deductions',
    ])
    expect(tasks.every((t) => t.status === 'open')).toBe(true)
  })

  it('returns a light checklist for inactive', () => {
    const tasks = generateTasks('inactive', START)
    expect(tasks.map((t) => t.label)).toEqual([
      'Archive listing documents',
      'Follow up with owner',
    ])
  })

  it('offsets task dates from the given stage-start date', () => {
    const tasks = generateTasks('proposal', START)
    const upload = tasks.find((t) => t.label === 'Upload executed listing agreement')
    expect(upload?.date).toBe('2026-01-03')
  })

  // The sparkle badge means "the assistant queued this", which is a different
  // thing from `autoGenerated` ("the system produced this deliverable", which
  // earns a Review button in the planner). Conflating them put a sparkle on
  // every completed underwrite and BOV.
  it('marks only assistant-queued tasks createdByAi, never system deliverables', () => {
    const stages: ListingStage[] = ['proposal', 'active', 'under-contract', 'closed', 'inactive']
    const all = stages.flatMap((s) => generateTasks(s, START))

    expect(all.filter((t) => t.createdByAi).map((t) => t.label)).toEqual([
      'Call owner to confirm pricing strategy',
      'Follow up with owner',
    ])
    // The system deliverables stay unflagged, however many of them complete.
    expect(all.filter((t) => t.autoGenerated).some((t) => t.createdByAi)).toBe(false)
  })

  // The Tasks page badges a task by the type derived from its label, so the
  // stage plans have to be worded such that every type is actually reachable —
  // otherwise the page only ever shows To-Do. Open tasks only: a type that
  // exists solely on completed work is invisible by default.
  it('covers every task type across the stage plans, in open work', () => {
    const stages: ListingStage[] = ['proposal', 'active', 'under-contract', 'closed', 'inactive']
    const openTypes = new Set(
      stages
        .flatMap((s) => generateTasks(s, START))
        .filter((t) => t.status !== 'complete')
        .map((t) => deriveTaskType(t.label)),
    )
    for (const type of Object.keys(TASK_TYPE_LABELS) as TaskTypeKey[]) {
      expect(openTypes, `no open seeded task derives the "${type}" type`).toContain(type)
    }
  })
})

describe('property stage seed', () => {
  const { properties, listings } = generateDataset()
  const dealPropertyIds = new Set(listings.map((l) => l.propertyId))

  it('gives a property a stage only when a deal sits on it', () => {
    for (const p of properties) {
      if (dealPropertyIds.has(p.id)) expect(p.status).not.toBeNull()
      // No deal means no stage — not `inactive`, which means a deal was lost.
      else expect(p.status).toBeNull()
    }
  })

  it('seeds a meaningful population of properties with no deal at all', () => {
    const noDeal = properties.filter((p) => p.status === null)
    expect(noDeal.length).toBeGreaterThanOrEqual(8)
    // And they must be ordinary records, not degenerate ones.
    for (const p of noDeal) expect(p.buildingSqFt).toBeGreaterThan(0)
  })

  it("matches each deal-bearing property's stage to a deal on it", () => {
    for (const l of listings) {
      const p = properties.find((x) => x.id === l.propertyId)
      expect(p?.status).not.toBeNull()
    }
  })
})

describe('property units + financial records seed', () => {
  const { properties } = generateDataset()

  it('gives every property at least one unit with a physical shell', () => {
    for (const p of properties) {
      expect(p.units.length).toBeGreaterThan(0)
      for (const u of p.units) {
        expect(u.sqft).toBeGreaterThan(0)
        expect(typeof u.label).toBe('string')
      }
    }
  })

  it('gives every property dated financial records, newest first, latest mirroring flat actuals', () => {
    for (const p of properties) {
      expect(p.financialRecords.length).toBeGreaterThan(0)
      const dates = p.financialRecords.map((r) => r.asOf)
      const sorted = [...dates].sort().reverse()
      expect(dates).toEqual(sorted) // newest-first
      const latest = p.financialRecords[0]
      expect(latest.noi).toBe(p.noi)
      expect(latest.capRate).toBe(p.capRate)
    }
  })

  it('derives occupancyPct from vacancy and gives a notes string', () => {
    for (const p of properties) {
      expect(p.occupancyPct).toBeGreaterThanOrEqual(0)
      expect(p.occupancyPct).toBeLessThanOrEqual(100)
      expect(typeof p.notes).toBe('string')
    }
  })

  it('makes each financial record internally consistent (NOI = EGI − OpEx, occupancy = 1 − vacancy)', () => {
    for (const p of properties) {
      for (const r of p.financialRecords) {
        expect(r.noi).toBe(r.effectiveGrossIncome - r.operatingExpenses)
        expect(Math.abs(r.occupancyPct - (1 - r.vacancyRate) * 100)).toBeLessThan(0.1)
      }
    }
  })

  it('varies figures year-to-year (history is not the same numbers copied down)', () => {
    // Income trends down into the past, so NOI is distinct per year for every
    // income-producing property. Land / zero-NOI assets stay flat at 0 — skip those.
    let checked = 0
    for (const p of properties) {
      if (p.noi <= 0) continue
      checked++
      expect(new Set(p.financialRecords.map((r) => r.noi)).size).toBeGreaterThan(1)
    }
    expect(checked).toBeGreaterThan(0) // guard against a vacuous pass
    // Vacancy drifts across years too (dataset-level, robust against a clamped edge case).
    expect(
      properties.some((p) => new Set(p.financialRecords.map((r) => r.vacancyRate)).size > 1),
    ).toBe(true)
  })
})

describe('unit sale history seed', () => {
  const { properties } = generateDataset()

  it('is newest-first with positive prices, consistent $/SF, and plausible cap rates', () => {
    let sawSome = false
    for (const p of properties) {
      for (const u of p.units) {
        expect(Array.isArray(u.saleHistory)).toBe(true)
        if (u.saleHistory.length > 0) sawSome = true
        const dates = u.saleHistory.map((s) => s.date)
        expect(dates).toEqual([...dates].sort().reverse()) // newest first
        for (const s of u.saleHistory) {
          expect(s.price).toBeGreaterThan(0)
          expect(s.capRateAtSale).toBeGreaterThan(0)
          expect(s.capRateAtSale).toBeLessThan(0.15)
          if (u.sqft > 0) expect(Math.abs(s.pricePerSf - s.price / u.sqft)).toBeLessThan(1)
        }
      }
    }
    expect(sawSome).toBe(true) // at least some units carry a sale history
  })
})

describe('lastActivityAt', () => {
  it("matches each hero's newest timeline beat, so the Last Activity filter is true", () => {
    // The fixtures pin lastActivityDaysAgo by hand (the arcs are hand-authored),
    // so this walks the real timeline and fails loudly if the two ever drift.
    const { contacts } = generateDataset()
    for (const c of contacts.filter((x) => x.heroKey)) {
      const newest = buildContactTimeline(c, [])
        .map((e) => Date.parse(e.timestamp))
        .sort((a, b) => b - a)[0]
      const activityAt = Date.parse(c.lastActivityAt ?? c.lastContactedAt!)
      // Same day — the fixture is day-granular, the arc carries a time of day.
      expect(Math.abs(newest - activityAt)).toBeLessThan(36 * 60 * 60 * 1000)
    }
  })

  it("puts Rosa's inbound voicemail inside the past-7-days bucket", () => {
    const { contacts } = generateDataset()
    const rosa = contacts.find((c) => c.heroKey === 'rosa')!
    // We last spoke 8 days ago — outside the bucket…
    const contactedAge = Date.now() - Date.parse(rosa.lastContactedAt!)
    expect(contactedAge).toBeGreaterThan(7 * 86_400_000)
    // …but her voicemail yesterday is what the filter reads.
    expect(matchesContactFilters(rosa, { ...emptyContactFilters(), lastActivity: '7d' })).toBe(true)
  })
})

describe('voucher approval seed', () => {
  const { listings } = generateDataset()

  it('gives every Approved voucher an approval, and no other voucher one', () => {
    // The whole reason `approval` is one nested object rather than two flat
    // nullable fields: the pair is all-or-nothing, and this is what says so.
    for (const l of listings) {
      const voucher = l.transaction.backOffice
      if (voucher.status === 'Approved') expect(voucher.approval).not.toBeNull()
      else expect(voucher.approval).toBeNull()
    }
  })

  it('names a reviewer who is actually on the roster', () => {
    const approved = listings
      .map((l) => l.transaction.backOffice)
      .filter((v) => v.approval !== null)
    expect(approved.length).toBeGreaterThan(0)
    for (const v of approved) {
      expect(findTeammate(v.approval!.reviewerId)).toBeDefined()
    }
  })

  it('never signs a voucher off before the deal closed', () => {
    for (const l of listings) {
      const voucher = l.transaction.backOffice
      if (!voucher.approval || !voucher.closeDate) continue
      expect(voucher.approval.approvedOn >= voucher.closeDate).toBe(true)
    }
  })
})

describe('voucher payers seed', () => {
  const { listings, contacts } = generateDataset()
  const contactIds = new Set(contacts.map((c) => c.id))

  it('points every receivable at a contact that exists', () => {
    for (const deal of listings) {
      for (const r of deal.transaction.backOffice.receivables) {
        expect(contactIds.has(r.payerContactId)).toBe(true)
      }
    }
  })

  it("lists every receivable's payer among the voucher's payers", () => {
    // The rule the Payers section depends on: a receivable cannot bill someone
    // the voucher has not named as a payer.
    for (const deal of listings) {
      const back = deal.transaction.backOffice
      for (const r of back.receivables) {
        expect(back.payerContactIds).toContain(r.payerContactId)
      }
    }
  })

  it('has no duplicate payers on a voucher', () => {
    for (const deal of listings) {
      const ids = deal.transaction.backOffice.payerContactIds
      expect(new Set(ids).size).toBe(ids.length)
    }
  })

  it('gives a voucher with nothing billed no payers', () => {
    // A lease suite is built by copying the building's voucher and clearing it.
    // The payer list is part of what gets cleared: the building's payers were
    // never billed on the suite, so a Draft suite listing them would name
    // parties nobody invoiced.
    for (const deal of listings) {
      const back = deal.transaction.backOffice
      if (back.receivables.length === 0) {
        expect(back.payerContactIds).toEqual([])
      }
    }
  })

  it('bills at least one voucher to a party on neither side of its deal', () => {
    // The Payers section exists because the payer is often nobody in the deal —
    // a corporate AP department, a holding company. A seller-payer does not show
    // that: the seller is a party. Excluding them here is what makes this test
    // guard the case the section was built for, rather than pass on a
    // split-commission receivable that was always there.
    const outsider = listings.some((deal) => {
      const parties = new Set([
        ...deal.buyerContactIds,
        ...deal.tenantContactIds,
        ...deal.sellerContactIds,
      ])
      return deal.transaction.backOffice.payerContactIds.some(
        (id) => !parties.has(id),
      )
    })
    expect(outsider).toBe(true)
  })
})

describe('voucher status seed', () => {
  const { listings } = generateDataset()

  it('leaves every voucher on an unclosed deal in Draft', () => {
    // A voucher is the broker's working document until the deal settles. There
    // is nothing to approve before a close, so Pending and Approved are not
    // states an open deal can reach — the stage decides, never a draw.
    for (const deal of listings) {
      if (deal.status === 'closed') continue
      expect(deal.transaction.backOffice.status).toBe('Draft')
    }
  })

  it('reaches all three states among the closed deals', () => {
    // Closed is the only stage that spans the whole lifecycle: the broker still
    // finalising it (Draft), submitted and waiting on the back office (Pending),
    // and signed off (Approved). `DEAL_PIPELINE` names the mix outright rather
    // than drawing it, so this pins that the list still covers every state.
    const reached = new Set(
      listings
        .filter((deal) => deal.status === 'closed')
        .map((deal) => deal.transaction.backOffice.status),
    )
    expect([...reached].sort()).toEqual(['Approved', 'Draft', 'Pending'])
  })

  it('bills an under-contract deal without crediting anything to it', () => {
    // The broker fills the voucher up as the deal moves, so an accepted buyer
    // is already billed by the time the deal is under contract — but nothing
    // has been received against it, which is what separates this from a closed
    // deal's receivables.
    //
    // Child spaces are excluded: `leaseSpaceFixtures` builds those by clearing
    // the shell's voucher and only refills it at Closed, and that module has to
    // stay faker-free.
    const underContract = listings.filter(
      (deal) =>
        deal.parentDealId === null &&
        deal.status === 'under-contract' &&
        deal.transaction.commissionAmount > 0,
    )
    expect(underContract.length).toBeGreaterThan(0)
    for (const deal of underContract) {
      const voucher = deal.transaction.backOffice
      expect(voucher.receivables).toHaveLength(1)
      expect(voucher.receivables[0].credited).toBe(0)
      expect(voucher.payerContactIds).toEqual([voucher.receivables[0].payerContactId])
    }
  })
})

describe('invoice seed', () => {
  const { listings } = generateDataset()

  it('gives every voucher past Draft an invoice, and no Draft voucher one', () => {
    // Sending the invoices is the last thing a broker does before submitting, so
    // the two states are exactly aligned. A Draft voucher with no invoices is
    // also what keeps the Invoices page's empty state reachable on a fresh seed.
    for (const deal of listings) {
      const voucher = deal.transaction.backOffice
      const count = deal.invoices?.length ?? 0
      if (voucher.status === 'Draft') expect(count).toBe(0)
      else expect(count).toBeGreaterThan(0)
    }
  })

  it('bills every invoice line against a receivable on that same voucher', () => {
    for (const deal of listings) {
      const ids = new Set(deal.transaction.backOffice.receivables.map((r) => r.id))
      for (const invoice of deal.invoices ?? []) {
        for (const line of invoice.lineItems) {
          expect(ids.has(line.receivableId)).toBe(true)
        }
      }
    }
  })

  it('bills one payer per invoice, and one the voucher names', () => {
    for (const deal of listings) {
      const payers = new Set(deal.transaction.backOffice.payerContactIds)
      for (const invoice of deal.invoices ?? []) {
        expect(payers.has(invoice.payerContactId)).toBe(true)
        const byLine = deal.transaction.backOffice.receivables.filter((r) =>
          invoice.lineItems.some((l) => l.receivableId === r.id),
        )
        expect(new Set(byLine.map((r) => r.payerContactId))).toEqual(
          new Set([invoice.payerContactId]),
        )
      }
    }
  })

  it('names a creator who is actually on the roster', () => {
    const invoices = listings.flatMap((l) => l.invoices ?? [])
    expect(invoices.length).toBeGreaterThan(0)
    for (const invoice of invoices) {
      expect(findTeammate(invoice.createdById)).toBeDefined()
    }
  })

  it('states the earliest of its lines as the invoice due date', () => {
    for (const invoice of listings.flatMap((l) => l.invoices ?? [])) {
      const earliest = invoice.lineItems
        .map((l) => l.dueDate)
        .sort()[0]
      expect(invoice.dueDate).toBe(earliest)
    }
  })

  it('agrees with the receivable it froze, since nothing has moved yet', () => {
    // At seed time a copy and its source must match. They are allowed to diverge
    // afterwards — that is the whole point of copying them — so this pins the
    // starting state rather than an invariant.
    for (const deal of listings) {
      const byId = new Map(deal.transaction.backOffice.receivables.map((r) => [r.id, r]))
      for (const invoice of deal.invoices ?? []) {
        for (const line of invoice.lineItems) {
          const r = byId.get(line.receivableId)!
          expect(line.amount).toBe(r.amount)
          expect(line.amountPaid).toBe(r.credited)
          expect(line.dueDate).toBe(r.dueDate)
        }
      }
    }
  })

  it('names each invoice file after its payer, numbered within the deal', () => {
    for (const deal of listings) {
      const names = (deal.invoices ?? []).map((i) => i.name)
      expect(new Set(names).size).toBe(names.length)
      for (const name of names) expect(name).toMatch(/_Invoice_\d+\.pdf$/)
    }
  })
})

describe('quickbooks sync seed', () => {
  const { listings, contacts } = generateDataset()

  it('flags every seeded contact, and both states appear', () => {
    const flags = contacts.map((c) => c.quickbooksSynced)
    for (const flag of flags) expect(typeof flag).toBe('boolean')
    expect(flags.filter(Boolean).length).toBeGreaterThan(0)
    expect(flags.filter((f) => f === false).length).toBeGreaterThan(0)
  })

  it('derives each contact flag from its id rather than drawing it', () => {
    // Pinning this is what protects the faker stream: the moment someone
    // replaces the hash with a `faker` call, every value seeded after the
    // contact loop moves, and the flagship story's contacts move with them.
    for (const contact of contacts) {
      expect(contact.quickbooksSynced).toBe(isQuickbooksSynced(contact.id))
    }
  })

  it('flags every receivable on every voucher', () => {
    const all = listings.flatMap((l) => l.transaction.backOffice.receivables)
    expect(all.length).toBeGreaterThan(0)
    for (const receivable of all) {
      expect(receivable.quickbooksSynced).toBe(isQuickbooksSynced(receivable.id))
    }
  })

  it('gives the receivables both states, so the badge column is never uniform', () => {
    const all = listings.flatMap((l) => l.transaction.backOffice.receivables)
    const synced = all.filter((r) => r.quickbooksSynced)
    expect(synced.length).toBeGreaterThan(0)
    expect(synced.length).toBeLessThan(all.length)
  })
})
