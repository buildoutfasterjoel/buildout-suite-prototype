describe('voucher payers seed', () => {
  const { listings, contacts } = generateDataset()
  const contactIds = new Set(contacts.map((c) => c.id))

  it('points every receivable at a contact that exists', () => {
    for (const deal of listings) {
      for (const r of deal.transaction.backOffice.receivables) {
        expect(contactIds.has(r.payerContactId)).toBe(true)
      }
    }
  })

  it("lists every receivable's payer among the voucher's payers", () => {
    // The rule the Payers section depends on: a receivable cannot bill someone
    // the voucher has not named as a payer.
    for (const deal of listings) {
      const back = deal.transaction.backOffice
      for (const r of back.receivables) {
        expect(back.payerContactIds).toContain(r.payerContactId)
      }
    }
  })

  it('has no duplicate payers on a voucher', () => {
    for (const deal of listings) {
      const ids = deal.transaction.backOffice.payerContactIds
      expect(new Set(ids).size).toBe(ids.length)
    }
  })

  it('gives a voucher with nothing billed no payers', () => {
    // A lease suite is built by copying the building's voucher and clearing it.
    // The payer list is part of what gets cleared: the building's payers were
    // never billed on the suite, so a Draft suite listing them would name
    // parties nobody invoiced.
    for (const deal of listings) {
      const back = deal.transaction.backOffice
      if (back.receivables.length === 0) {
        expect(back.payerContactIds).toEqual([])
      }
    }
  })

  it('bills at least one voucher to a party on neither side of its deal', () => {
    // The Payers section exists because the payer is often nobody in the deal —
    // a corporate AP department, a holding company. A seller-payer does not show
    // that: the seller is a party. Excluding them here is what makes this test
    // guard the case the section was built for, rather than pass on a
    // split-commission receivable that was always there.
    const outsider = listings.some((deal) => {
      const parties = new Set([
        ...deal.buyerContactIds,
        ...deal.tenantContactIds,
        ...deal.sellerContactIds,
      ])
      return deal.transaction.backOffice.payerContactIds.some(
        (id) => !parties.has(id),
      )
    })
    expect(outsider).toBe(true)
  })
})

describe('voucher status seed', () => {
  const { listings } = generateDataset()

  it('leaves every voucher on an unclosed deal in Draft', () => {
    // A voucher is the broker's working document until the deal settles. There
    // is nothing to approve before a close, so Pending and Approved are not
    // states an open deal can reach — the stage decides, never a draw.
    for (const deal of listings) {
      if (deal.status === 'closed') continue
      expect(deal.transaction.backOffice.status).toBe('Draft')
    }
  })

  it('reaches all three states among the closed deals', () => {
    // Closed is the only stage that spans the whole lifecycle: the broker still
    // finalising it (Draft), submitted and waiting on the back office (Pending),
    // and signed off (Approved). `DEAL_PIPELINE` names the mix outright rather
    // than drawing it, so this pins that the list still covers every state.
    const reached = new Set(
      listings
        .filter((deal) => deal.status === 'closed')
        .map((deal) => deal.transaction.backOffice.status),
    )
    expect([...reached].sort()).toEqual(['Approved', 'Draft', 'Pending'])
  })

  it('bills an under-contract deal without crediting anything to it', () => {
    // The broker fills the voucher up as the deal moves, so an accepted buyer
    // is already billed by the time the deal is under contract — but nothing
    // has been received against it, which is what separates this from a closed
    // deal's receivables.
    //
    // Child spaces are excluded: `leaseSpaceFixtures` builds those by clearing
    // the shell's voucher and only refills it at Closed, and that module has to
    // stay faker-free.
    const underContract = listings.filter(
      (deal) =>
        deal.parentDealId === null &&
        deal.status === 'under-contract' &&
        deal.transaction.commissionAmount > 0,
    )
    expect(underContract.length).toBeGreaterThan(0)
    for (const deal of underContract) {
      const voucher = deal.transaction.backOffice
      expect(voucher.receivables).toHaveLength(1)
      expect(voucher.receivables[0].credited).toBe(0)
      expect(voucher.payerContactIds).toEqual([voucher.receivables[0].payerContactId])
    }
  })
})

describe('deposit seed', () => {
  const { listings } = generateDataset()

  it('puts exactly one deposit behind every credited receivable', () => {
    // A credited row with nothing under it would expand to an empty child table
    // and read as money that arrived from nowhere.
    const credited = listings.flatMap((deal) =>
      deal.transaction.backOffice.receivables.filter((r) => r.credited > 0),
    )
    expect(credited.length).toBeGreaterThan(0)
    for (const deal of listings) {
      const voucher = deal.transaction.backOffice
      const paid = new Set(
        voucher.receivables.filter((r) => r.credited > 0).map((r) => r.id),
      )
      const depositedAgainst = (voucher.deposits ?? []).flatMap((d) =>
        d.receivableAllocations.map((a) => a.targetId),
      )
      expect(new Set(depositedAgainst)).toEqual(paid)
      expect(depositedAgainst).toHaveLength(paid.size)
    }
  })

  it('keeps stored credited equal to what its deposits allocated', () => {
    // `credited` is a stored running total rather than a sum computed from the
    // deposits — see `applyDeposit` for why. This is what stops the two drifting.
    for (const deal of listings) {
      const voucher = deal.transaction.backOffice
      const allocated = new Map<string, number>()
      for (const deposit of voucher.deposits ?? []) {
        for (const a of deposit.receivableAllocations) {
          allocated.set(a.targetId, (allocated.get(a.targetId) ?? 0) + a.amount)
        }
      }
      for (const r of voucher.receivables) {
        expect(allocated.get(r.id) ?? 0).toBe(r.credited)
      }
    }
  })

  it('never credits a receivable past what it billed', () => {
    for (const deal of listings) {
      for (const r of deal.transaction.backOffice.receivables) {
        expect(r.credited).toBeLessThanOrEqual(r.amount)
      }
    }
  })

  it('leaves every seeded deduction uncovered', () => {
    // Deliberate: crediting them in the seed would mean splitting each deposit
    // across two tables to keep the two consistent, which is arithmetic standing
    // in for a deposit nobody applied.
    for (const deal of listings) {
      for (const deposit of deal.transaction.backOffice.deposits ?? []) {
        expect(deposit.deductionAllocations).toEqual([])
      }
      for (const d of deal.transaction.backOffice.preSplitDeductions) {
        expect(d.covered).toBeNull()
      }
    }
  })

  it('gives every deposit a reference, unique within its voucher', () => {
    // No deposit may show an empty reference column, seeded or entered. The save
    // path generates one when the broker leaves the field blank; the seed uses
    // the same generator, so the two are the same kind of thing.
    for (const deal of listings) {
      const refs = (deal.transaction.backOffice.deposits ?? []).map(
        (d) => d.referenceNumber,
      )
      for (const ref of refs) expect(ref).toMatch(/^[1-9]\d{3}$/)
      expect(new Set(refs).size).toBe(refs.length)
    }
  })

  it('dates each deposit after the line it paid', () => {
    for (const deal of listings) {
      const byId = new Map(deal.transaction.backOffice.receivables.map((r) => [r.id, r]))
      for (const deposit of deal.transaction.backOffice.deposits ?? []) {
        const target = byId.get(deposit.receivableAllocations[0].targetId)!
        expect(deposit.date > target.dueDate).toBe(true)
      }
    }
  })
})

describe('payable seed', () => {
  const { listings } = generateDataset()
  const vouchers = listings.map((deal) => deal.transaction.backOffice)

  it('raises payables on Approved vouchers and on no others', () => {
    // The rule the whole record turns on: there is nothing to pay out of a
    // commission nobody has signed off. Draft vouchers carrying deposits are
    // common in this seed, and they must carry no payables.
    const approved = vouchers.filter((v) => v.status === 'Approved')
    expect(approved.length).toBeGreaterThan(0)
    for (const voucher of vouchers) {
      const has = (voucher.payables ?? []).length > 0
      if (voucher.status !== 'Approved') expect(has).toBe(false)
    }
    expect(approved.some((v) => (v.payables ?? []).length > 0)).toBe(true)
  })

  it('names a broker and a deposit that both exist on the deal', () => {
    for (const deal of listings) {
      const brokerIds = new Set(
        [...deal.internalBrokers, ...deal.outsideBrokers].map((b) => b.id),
      )
      const voucher = deal.transaction.backOffice
      const depositIds = new Set((voucher.deposits ?? []).map((d) => d.id))
      for (const payable of voucher.payables ?? []) {
        expect(brokerIds.has(payable.brokerId)).toBe(true)
        expect(depositIds.has(payable.depositId)).toBe(true)
      }
    }
  })

  it('gives each broker their share of what arrived, and no more', () => {
    // The whole-voucher denominator, checked from the other end: however many
    // deposits a voucher was paid in, a broker's payables must add up to their
    // share of the money received — never to a full gross per deposit.
    for (const deal of listings) {
      const voucher = deal.transaction.backOffice
      if (!voucher.payables?.length) continue
      const received = (voucher.deposits ?? []).reduce((t, d) => t + d.amount, 0)
      for (const broker of [...deal.internalBrokers, ...deal.outsideBrokers]) {
        const owed = voucher.payables
          .filter((p) => p.brokerId === broker.id)
          .reduce((total, p) => total + p.grossAmount, 0)
        const expected = payableShare({
          broker,
          depositAmount: received,
          allReceivables: voucher.receivables,
        })
        expect(owed).toBeCloseTo(expected, 1)
        expect(owed).toBeLessThanOrEqual(broker.grossCommission + 0.01)
      }
    }
  })

  it('dates a payable from the deposit that funded it', () => {
    for (const deal of listings) {
      const voucher = deal.transaction.backOffice
      const byId = new Map((voucher.deposits ?? []).map((d) => [d.id, d]))
      for (const payable of voucher.payables ?? []) {
        expect(payable.date).toBe(byId.get(payable.depositId)!.date)
      }
    }
  })

  it('never pays out more than a payable is worth', () => {
    for (const voucher of vouchers) {
      for (const payable of voucher.payables ?? []) {
        expect(payableGrossPaid(payable)).toBeLessThanOrEqual(payable.grossAmount)
        expect(payableBalance(payable)).toBeGreaterThanOrEqual(0)
      }
    }
  })

  it('part-pays some payables and leaves others open', () => {
    // Both states have to appear, or the Gross Paid and Net Paid columns cannot
    // show what they mean.
    const all = vouchers.flatMap((v) => v.payables ?? [])
    expect(all.some((p) => p.payments.length > 0)).toBe(true)
    expect(all.some((p) => p.payments.length === 0)).toBe(true)
    expect(
      all.some((p) => p.payments.some((x) => x.deductions.length > 0)),
    ).toBe(true)
  })

  it('dates a payment after the payable it settles', () => {
    for (const voucher of vouchers) {
      for (const payable of voucher.payables ?? []) {
        for (const payment of payable.payments) {
          expect(payment.date > payable.date).toBe(true)
        }
      }
    }
  })
})

