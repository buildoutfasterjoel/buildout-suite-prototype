describe('deposit check number seed', () => {
  const { listings } = generateDataset()
  const deposits = listings.flatMap(
    (deal) => deal.transaction.backOffice.deposits ?? [],
  )

  it('leaves both states in the book, so the Check # column is never uniform', () => {
    expect(deposits.length).toBeGreaterThan(0)
    // A column that is all dashes, or all numbers, cannot show that the field
    // is optional — which is the one thing it has to say.
    expect(deposits.some((d) => d.checkNumber)).toBe(true)
    expect(deposits.some((d) => !d.checkNumber)).toBe(true)
  })

  it('writes no empty check number, only an absent one', () => {
    for (const deposit of deposits) {
      if ('checkNumber' in deposit) expect(deposit.checkNumber).toBeTruthy()
    }
  })

  it('gives every deposit a reference, cheque or not', () => {
    for (const deposit of deposits) {
      expect(deposit.referenceNumber).toBeTruthy()
    }
  })

  // Both were first hashed from the bare receivable id into the same range, so
  // every cheque row read "Ref 1898 / Check 1898" — two fields whose whole
  // point is that they are not the same fact, printed as if they were.
  it('never prints a cheque number equal to its own reference', () => {
    for (const deposit of deposits) {
      if (!deposit.checkNumber) continue
      expect(deposit.checkNumber).not.toBe(deposit.referenceNumber)
    }
  })
})

describe('commission split seed', () => {
  const { listings } = generateDataset()

  /** Pre-split deductions come off the gross before any broker splits it. */
  function netCommission(deal: (typeof listings)[number]): number {
    const back = deal.transaction.backOffice
    const deducted = back.preSplitDeductions.reduce((t, d) => t + d.amount, 0)
    return deal.transaction.commissionAmount - deducted
  }

  it('splits one pool between both sides, so the percentages sum to 100', () => {
    for (const deal of listings) {
      const brokers = [...deal.outsideBrokers, ...deal.internalBrokers]
      if (brokers.length === 0) continue
      const pct = brokers.reduce((t, b) => t + b.commissionSplitPct, 0)
      expect(pct, deal.name).toBe(100)
    }
  })

  /**
   * The regression this suite exists for.
   *
   * The seed used to give the internal broker 100% of the net commission and
   * add the outside broker's 40-60% on top, so a co-broked deal's brokers were
   * owed 135-160% of what the deal had billed. Nothing surfaced it until the
   * Deposits index summed a voucher's payables against the deposit that funded
   * them, where it read as a $0.00 Collected House Split.
   */
  it('never owes its brokers more than the commission they are splitting', () => {
    for (const deal of listings) {
      const brokers = [...deal.outsideBrokers, ...deal.internalBrokers]
      if (brokers.length === 0) continue
      const owed = brokers.reduce((t, b) => t + b.grossCommission, 0)
      expect(owed, deal.name).toBeLessThanOrEqual(netCommission(deal))
    }
  })

  it('leaves co-broked deals in the book, or the rule above proves nothing', () => {
    const coBroked = listings.filter((deal) => deal.outsideBrokers.length > 0)
    expect(coBroked.length).toBeGreaterThan(0)
    // And the internal broker on one really is taking less than the whole pool.
    for (const deal of coBroked) {
      for (const broker of deal.internalBrokers) {
        expect(broker.commissionSplitPct, deal.name).toBeLessThan(100)
      }
    }
  })
})

describe('invoice seed', () => {
  const { listings } = generateDataset()

  it('gives every voucher past Draft an invoice, and no Draft voucher one', () => {
    // Sending the invoices is the last thing a broker does before submitting, so
    // the two states are exactly aligned. A Draft voucher with no invoices is
    // also what keeps the Invoices page's empty state reachable on a fresh seed.
    for (const deal of listings) {
      const voucher = deal.transaction.backOffice
      const count = deal.invoices?.length ?? 0
      if (voucher.status === 'Draft') expect(count).toBe(0)
      else expect(count).toBeGreaterThan(0)
    }
  })

  it('bills every invoice line against a receivable on that same voucher', () => {
    for (const deal of listings) {
      const ids = new Set(deal.transaction.backOffice.receivables.map((r) => r.id))
      for (const invoice of deal.invoices ?? []) {
        for (const line of invoice.lineItems) {
          expect(ids.has(line.receivableId)).toBe(true)
        }
      }
    }
  })

  it('bills one payer per invoice, and one the voucher names', () => {
    for (const deal of listings) {
      const payers = new Set(deal.transaction.backOffice.payerContactIds)
      for (const invoice of deal.invoices ?? []) {
        expect(payers.has(invoice.payerContactId)).toBe(true)
        const byLine = deal.transaction.backOffice.receivables.filter((r) =>
          invoice.lineItems.some((l) => l.receivableId === r.id),
        )
        expect(new Set(byLine.map((r) => r.payerContactId))).toEqual(
          new Set([invoice.payerContactId]),
        )
      }
    }
  })

  it('names a creator who is actually on the roster', () => {
    const invoices = listings.flatMap((l) => l.invoices ?? [])
    expect(invoices.length).toBeGreaterThan(0)
    for (const invoice of invoices) {
      expect(findTeammate(invoice.createdById)).toBeDefined()
    }
  })

  it('states the earliest of its lines as the invoice due date', () => {
    for (const invoice of listings.flatMap((l) => l.invoices ?? [])) {
      const earliest = invoice.lineItems
        .map((l) => l.dueDate)
        .sort()[0]
      expect(invoice.dueDate).toBe(earliest)
    }
  })

  it('agrees with the receivable it froze, since nothing has moved yet', () => {
    // At seed time a copy and its source must match. They are allowed to diverge
    // afterwards — that is the whole point of copying them — so this pins the
    // starting state rather than an invariant.
    for (const deal of listings) {
      const byId = new Map(deal.transaction.backOffice.receivables.map((r) => [r.id, r]))
      for (const invoice of deal.invoices ?? []) {
        for (const line of invoice.lineItems) {
          const r = byId.get(line.receivableId)!
          expect(line.amount).toBe(r.amount)
          expect(line.amountPaid).toBe(r.credited)
          expect(line.dueDate).toBe(r.dueDate)
        }
      }
    }
  })

  it('names each invoice file after its payer, numbered within the deal', () => {
    for (const deal of listings) {
      const names = (deal.invoices ?? []).map((i) => i.name)
      expect(new Set(names).size).toBe(names.length)
      for (const name of names) expect(name).toMatch(/_Invoice_\d+\.pdf$/)
    }
  })
})

describe('quickbooks sync seed', () => {
  const { listings, contacts } = generateDataset()

  it('flags every seeded contact, and both states appear', () => {
    const flags = contacts.map((c) => c.quickbooksSynced)
    for (const flag of flags) expect(typeof flag).toBe('boolean')
    expect(flags.filter(Boolean).length).toBeGreaterThan(0)
    expect(flags.filter((f) => f === false).length).toBeGreaterThan(0)
  })

  it('derives each contact flag from its id rather than drawing it', () => {
    // Pinning this is what protects the faker stream: the moment someone
    // replaces the hash with a `faker` call, every value seeded after the
    // contact loop moves, and the flagship story's contacts move with them.
    for (const contact of contacts) {
      expect(contact.quickbooksSynced).toBe(isQuickbooksSynced(contact.id))
    }
  })

  it('flags every receivable from its own id AND its payer', () => {
    const byId = new Map(contacts.map((c) => [c.id, c]))
    const all = listings.flatMap((l) => l.transaction.backOffice.receivables)
    expect(all.length).toBeGreaterThan(0)
    for (const receivable of all) {
      const payer = byId.get(receivable.payerContactId)
      expect(receivable.quickbooksSynced).toBe(
        payer?.quickbooksSynced === true && isQuickbooksSynced(receivable.id),
      )
    }
  })

  it('never shows a receivable in QuickBooks under a payer that is not', () => {
    // The invariant the whole chain exists for. QuickBooks holds no A/R record
    // against a customer it has never heard of, and now that both states are
    // visible, such a pair would be on screen one column apart.
    const byId = new Map(contacts.map((c) => [c.id, c]))
    for (const deal of listings) {
      for (const receivable of deal.transaction.backOffice.receivables) {
        if (!receivable.quickbooksSynced) continue
        expect(byId.get(receivable.payerContactId)?.quickbooksSynced).toBe(true)
      }
    }
  })

  it('never shows an invoice in QuickBooks above a receivable that is not', () => {
    // Same invariant, one link further down. The invoice badge is derived, so
    // this is really a check that the seed cannot produce an invoice whose lines
    // point at receivables it disagrees with.
    for (const deal of listings) {
      const receivables = deal.transaction.backOffice.receivables
      for (const invoice of deal.invoices ?? []) {
        if (!invoiceQuickbooksSynced(invoice.lineItems, receivables)) continue
        for (const line of invoice.lineItems) {
          const billed = receivables.find((r) => r.id === line.receivableId)
          expect(billed?.quickbooksSynced).toBe(true)
        }
      }
    }
  })

  it('leaves both states reachable on the invoices page', () => {
    const states = new Set(
      listings.flatMap((l) =>
        (l.invoices ?? []).map((i) =>
          invoiceQuickbooksSynced(i.lineItems, l.transaction.backOffice.receivables),
        ),
      ),
    )
    expect(states).toEqual(new Set([true, false]))
  })

  it('gives the receivables both states, so the badge column is never uniform', () => {
    const all = listings.flatMap((l) => l.transaction.backOffice.receivables)
    const synced = all.filter((r) => r.quickbooksSynced)
    expect(synced.length).toBeGreaterThan(0)
    expect(synced.length).toBeLessThan(all.length)
  })
})

describe('deal team seed', () => {
  const { listings } = generateDataset()
  // Spaces clone their parent's brokers; the rules below are about the deals
  // that generate their own.
  const deals = listings.filter((l) => !l.parentDealId)

  it('makes a broker-created deal one of that broker\'s own', () => {
    // The bug this pins: the creator used to be hashed from the deal id while
    // the broker was hashed from the broker row's uuid, so a deal could read
    // "created by Sarah Chen" over a broker list holding only Marcus Patel.
    // Marketing-opened deals are the deliberate exception below.
    for (const l of deals.filter((x) => !marketingCreatedDeal(x.id))) {
      const creator = findTeammate(l.createdById)
      expect(creator, l.id).toBeDefined()
      expect(
        l.internalBrokers.map((b) => b.name),
        `${l.name} created by ${creator?.name}`,
      ).toContain(creator!.name)
    }
  })

  it('leaves a marketing-opened deal to a broker, and shares it back', () => {
    // Maya can open a deal and cannot hold one, so she is never on its broker
    // list. Without the share she would have typed in a deal and lost it.
    //
    // A space's share hangs on its building: marketing is the building's, so
    // `dealAccessFor` reads the shell's list for a space and would never see a
    // share written on the space itself.
    const shares = seedDealShares(listings)
    const opened = deals.filter((l) => marketingCreatedDeal(l.id))
    expect(opened.length).toBeGreaterThanOrEqual(1)
    for (const l of opened) {
      expect(l.createdById, l.name).toBe('maya-brooks')
      expect(l.internalBrokers.map((b) => b.name), l.name).not.toContain('Maya Brooks')
      expect(
        (shares.get(l.parentDealId ?? l.id) ?? []).map((s) => s.member.id),
        l.name,
      ).toContain('maya-brooks')
    }

    // `deals` above excludes spaces, so that loop never sees one — and a space
    // is the whole point of this change. Its share lands on its building, so
    // check that shape directly. Filtered on `createdById` rather than on
    // `marketingCreatedDeal`, because `createdById` is the condition
    // `seedDealShares` actually grants on.
    const openedSpaces = listings.filter(
      (l) => l.parentDealId != null && l.createdById === 'maya-brooks',
    )
    expect(openedSpaces.length).toBeGreaterThanOrEqual(1)
    for (const l of openedSpaces) {
      expect(
        (shares.get(l.parentDealId as string) ?? []).map((s) => s.member.id),
        l.name,
      ).toContain('maya-brooks')
    }
  })

  it('writes no share onto a space', () => {
    const shares = seedDealShares(listings)
    const spaceIds = listings.filter((l) => l.parentDealId != null).map((l) => l.id)
    expect(spaceIds.length).toBeGreaterThan(0)
    for (const id of spaceIds) expect(shares.has(id), id).toBe(false)
  })

  it('seeds a minority of deals with a second internal broker', () => {
    const coBroked = deals.filter((l) => l.internalBrokers.length > 1)
    // Enough that the voucher's private-payout marker has something to hide...
    expect(coBroked.length).toBeGreaterThanOrEqual(2)
    // ...and few enough that a single broker is still the norm.
    expect(coBroked.length).toBeLessThan(deals.length / 2)
  })

  it('gives a co-brokered deal two different people, both on the roster', () => {
    for (const l of deals.filter((x) => x.internalBrokers.length > 1)) {
      const names = l.internalBrokers.map((b) => b.name)
      expect(new Set(names).size, l.name).toBe(names.length)
      for (const b of l.internalBrokers) {
        expect(b.personalSplitPct, `${l.name}/${b.name}`).toBeGreaterThan(0)
        expect(COMMISSION_PLANS, `${l.name}/${b.name}`).toContain(b.commissionPlan)
      }
    }
  })

  it('splits a co-brokered deal without losing or inventing a dollar', () => {
    // The second broker takes the remainder rather than a second rounding, so
    // the pair still sums to 100% and the voucher's unallocated gate reads zero.
    // A proposal-stage deal can carry no commission at all, and 0 split two ways
    // is 0 and 0 — that is the split working, not failing.
    for (const l of deals.filter((x) => x.internalBrokers.length > 1)) {
      const pctTotal = l.internalBrokers.reduce((t, b) => t + b.commissionSplitPct, 0)
      const outside = l.outsideBrokers.reduce((t, b) => t + b.commissionSplitPct, 0)
      expect(pctTotal + outside, l.name).toBe(100)
      for (const b of l.internalBrokers) {
        expect(b.grossCommission, `${l.name}/${b.name}`).toBeGreaterThanOrEqual(0)
      }
    }
  })

  it('gives at least one co-brokered deal real money on both rows', () => {
    // Otherwise the private-payout marker has a demo that reads "$0 vs locked",
    // which shows nothing.
    const withMoney = deals.filter(
      (l) =>
        l.internalBrokers.length > 1 &&
        l.internalBrokers.every((b) => b.grossCommission > 0),
    )
    expect(withMoney.length).toBeGreaterThanOrEqual(1)
  })
})
